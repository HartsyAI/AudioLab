namespace AudioLab.Web.Components;

/// <summary>The looks of <see cref="Button"/>.</summary>
public enum ButtonVariant
{
    /// <summary>A raised control.</summary>
    Default,

    /// <summary>The one main action of a panel or dialog, in the accent colour.</summary>
    Primary,

    /// <summary>A destructive action, in the record colour; never the default action.</summary>
    Danger,

    /// <summary>A square control that holds only an icon; it needs a name for its tooltip and its accessible name.</summary>
    Icon,
}
